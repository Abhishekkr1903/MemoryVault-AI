# ==================================================
# TOOL 1 — SEARCH MEMORIES
# ==================================================

def search_memory(
    query: str,
    search_scope: str = "All Memories",
    current_document_id: int | None = None,
    selected_document_ids: list[int] | None = None,
):
    """
    Search MemoryVault memories.

    Parameters
    ----------
    query:
        Search query generated by the Agent.

    search_scope:
        One of:
            - Current Memory
            - Selected Memories
            - All Memories

    current_document_id:
        Currently selected document.

    selected_document_ids:
        Documents selected by the user.
    """

    # ==================================================
    # CURRENT MEMORY
    # ==================================================

    if search_scope == "Current Memory":

        if current_document_id is None:

            return {
                "success": False,
                "message": (
                    "No current memory is selected."
                ),
                "results": [],
            }

        document_ids = [
            current_document_id
        ]

    # ==================================================
    # SELECTED MEMORIES
    # ==================================================

    elif search_scope == "Selected Memories":

        if not selected_document_ids:

            return {
                "success": False,
                "message": (
                    "No memories were selected."
                ),
                "results": [],
            }

        document_ids = (
            selected_document_ids
        )

    # ==================================================
    # ALL MEMORIES
    # ==================================================

    else:

        document_ids = None

    # ==================================================
    # RUN EXISTING RAG
    # ==================================================

    from rag.memory_retriever import (
        retrieve_memories,
    )

    results = retrieve_memories(
        question=query,
        document_ids=document_ids,
        top_k=5,
    )

    # ==================================================
    # NO RESULTS
    # ==================================================

    if not results:

        return {
            "success": True,
            "message": (
                "No relevant information "
                "was found in the selected memories."
            ),
            "results": [],
        }

    # ==================================================
    # RETURN RESULTS
    # ==================================================

    return {
        "success": True,
        "results": results,
    }
