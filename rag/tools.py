# TOOL 3 — GET DOCUMENT INFO
# ==================================================

def get_document_info(
    document_id: int,
):
    """
    Get metadata for a specific memory/document.
    """

    documents = db.get_documents_with_metadata()

    for document in documents:

        if document[0] == document_id:

            return {
                "success": True,
                "document": {
                    "document_id": document[0],
                    "filename": document[1],
                    "file_path": document[2],
                    "created_at": document[3],
                    "category": document[4],
                    "summary": document[5],
                    "keywords": document[6],
                    "language": document[7],
                },
            }

    return {
        "success": False,
        "message": (
            f"No document found with ID {document_id}."
        ),
    }


