# TOOL 2 — LIST MEMORIES
# ==================================================

def list_memories():
    """
    List all memories stored in MemoryVault.

    This does NOT perform semantic search.
    It directly reads the document database.
    """

    documents = db.get_documents_with_metadata()

    memories = []

    for document in documents:

        document_id = document[0]
        filename = document[1]
        created_at = document[3]
        category = document[4]
        summary = document[5]
        keywords = document[6]
        language = document[7]

        memories.append(
            {
                "document_id": document_id,
                "filename": filename,
                "created_at": created_at,
                "category": category,
                "summary": summary,
                "keywords": keywords,
                "language": language,
            }
        )

    return {
        "success": True,
        "count": len(memories),
        "memories": memories,
    }


